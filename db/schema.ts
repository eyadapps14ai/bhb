// Postgres schema, applied idempotently on first connection. The advisory lock
// stops several Cloud Run instances from racing to create the same tables.
export const SCHEMA = `
BEGIN;
SELECT pg_advisory_xact_lock(72310);
CREATE TABLE IF NOT EXISTS offices (
  id text PRIMARY KEY,
  owner text NOT NULL,
  code text NOT NULL,
  data text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS office_owner_code ON offices (owner, code);
CREATE TABLE IF NOT EXISTS payments (
  id text PRIMARY KEY,
  owner text NOT NULL,
  office_id text REFERENCES offices (id),
  data text NOT NULL
);
CREATE INDEX IF NOT EXISTS payment_owner ON payments (owner);
CREATE INDEX IF NOT EXISTS payment_office ON payments (office_id);
CREATE TABLE IF NOT EXISTS documents (
  id text PRIMARY KEY,
  owner text NOT NULL,
  office_id text NOT NULL REFERENCES offices (id),
  payment_id text REFERENCES payments (id),
  name text NOT NULL,
  category text NOT NULL,
  mime text NOT NULL,
  size integer NOT NULL,
  key text NOT NULL,
  created text NOT NULL
);
CREATE INDEX IF NOT EXISTS document_owner ON documents (owner);
CREATE INDEX IF NOT EXISTS document_office ON documents (office_id);
CREATE TABLE IF NOT EXISTS leases (
  id text PRIMARY KEY,
  owner text NOT NULL,
  office_id text NOT NULL REFERENCES offices (id),
  data text NOT NULL
);
CREATE INDEX IF NOT EXISTS lease_owner_office ON leases (owner, office_id);
CREATE TABLE IF NOT EXISTS employee_requests (
  id text PRIMARY KEY,
  owner text NOT NULL,
  data text NOT NULL
);
CREATE INDEX IF NOT EXISTS employee_request_owner ON employee_requests (owner);
CREATE TABLE IF NOT EXISTS employees (
  id text PRIMARY KEY,
  owner text NOT NULL,
  data text NOT NULL
);
CREATE INDEX IF NOT EXISTS employee_owner ON employees (owner);
CREATE TABLE IF NOT EXISTS email_connections (
  id text PRIMARY KEY,
  owner text NOT NULL,
  data text NOT NULL
);
CREATE INDEX IF NOT EXISTS email_connection_owner ON email_connections (owner);
CREATE TABLE IF NOT EXISTS invoice_issuers (
  id text PRIMARY KEY,
  owner text NOT NULL,
  data text NOT NULL
);
CREATE TABLE IF NOT EXISTS invoices (
  seq integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id text NOT NULL UNIQUE,
  owner text NOT NULL,
  office_id text NOT NULL REFERENCES offices (id),
  data text NOT NULL
);
CREATE INDEX IF NOT EXISTS invoice_owner ON invoices (owner);
CREATE UNIQUE INDEX IF NOT EXISTS invoice_owner_payment ON invoices (owner, ((data::jsonb) ->> 'paymentId'));
-- Invoice numbers run per branch and year; older invoices without a number keep their sequence.
CREATE UNIQUE INDEX IF NOT EXISTS invoice_branch_year_number ON invoices (owner, ((data::jsonb) ->> 'branch'), (substr((data::jsonb) ->> 'issueDate', 1, 4)), ((data::jsonb) ->> 'number'));
CREATE TABLE IF NOT EXISTS users (
  id text PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password text NOT NULL,
  data text NOT NULL,
  created text NOT NULL
);
CREATE TABLE IF NOT EXISTS roles (
  id text PRIMARY KEY,
  data text NOT NULL
);
CREATE TABLE IF NOT EXISTS enquiries (
  id text PRIMARY KEY,
  created text NOT NULL,
  status text NOT NULL,
  sender text NOT NULL,
  data text NOT NULL
);
CREATE INDEX IF NOT EXISTS enquiry_created ON enquiries (created);
CREATE INDEX IF NOT EXISTS enquiry_sender ON enquiries (sender);
CREATE TABLE IF NOT EXISTS claude_keys (
  id text PRIMARY KEY,
  user_id text NOT NULL,
  hash text NOT NULL UNIQUE,
  label text NOT NULL,
  created text NOT NULL,
  last_used text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS claude_key_user ON claude_keys (user_id);
CREATE TABLE IF NOT EXISTS oauth_clients (
  id text PRIMARY KEY,
  data text NOT NULL,
  created text NOT NULL
);
CREATE TABLE IF NOT EXISTS oauth_codes (
  hash text PRIMARY KEY,
  data text NOT NULL,
  expires text NOT NULL
);
CREATE TABLE IF NOT EXISTS oauth_grants (
  id text PRIMARY KEY,
  user_id text NOT NULL,
  client_id text NOT NULL,
  access_hash text NOT NULL UNIQUE,
  access_expires text NOT NULL,
  refresh_hash text NOT NULL UNIQUE,
  prev_refresh_hash text NOT NULL DEFAULT '',
  refresh_expires text NOT NULL,
  created text NOT NULL,
  last_used text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS oauth_grant_user ON oauth_grants (user_id);
CREATE TABLE IF NOT EXISTS sign_in_failures (
  key text NOT NULL,
  at text NOT NULL
);
CREATE INDEX IF NOT EXISTS sign_in_failure_key ON sign_in_failures (key, at);
-- To-dos a manager sends to a person (assignee = their user id); shown on that person's My dashboard.
CREATE TABLE IF NOT EXISTS tasks (
  id text PRIMARY KEY,
  owner text NOT NULL,
  assignee text NOT NULL,
  data text NOT NULL
);
CREATE INDEX IF NOT EXISTS task_assignee ON tasks (owner, assignee);
-- One-time data changes, each recorded so it never runs twice (a later change by an admin is kept).
CREATE TABLE IF NOT EXISTS migrations (
  id text PRIMARY KEY,
  at text NOT NULL
);
-- Owner's decision (2026-10-17): the Sales role does not see the Sales commission page.
UPDATE roles SET data = jsonb_set(data::jsonb, '{pages,sales}', '"none"')::text WHERE id = 'sales' AND NOT EXISTS (SELECT 1 FROM migrations WHERE id = 'sales-role-hides-commission');
INSERT INTO migrations (id, at) VALUES ('sales-role-hides-commission', now()::text) ON CONFLICT (id) DO NOTHING;
COMMIT;
`;
